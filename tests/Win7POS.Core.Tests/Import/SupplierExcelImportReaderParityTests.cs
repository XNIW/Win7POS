    public void ReadFirstWorksheet_XlsxSemanticCorpus_PreservesBaseline()
    {
        using var culture = new CultureScope(CultureInfo.InvariantCulture);
        var path = TempPath(".xlsx");
        try
        {
            WriteSemanticWorkbook(path);

            Assert.AreEqual(2, SupplierExcelImportReader.CountWorksheets(path));
            var table = SupplierExcelImportReader.ReadFirstWorksheet(path);

            Assert.AreEqual("Semantic First", table.SheetName);
            Assert.IsTrue(table.HasHeader);
            Assert.AreEqual(3, table.DataRowIndex);
            Assert.AreEqual(1, table.DroppedSummaryRows);
            Assert.AreEqual(12, table.Columns.Count);
            CollectionAssert.AreEqual(
                new[]
                {
                    AndroidImportKeys.Barcode,
                    AndroidImportKeys.ItemNumber,
                    AndroidImportKeys.ProductName,
                    AndroidImportKeys.SecondProductName,
                    AndroidImportKeys.PurchasePrice,
                    AndroidImportKeys.RetailPrice,
                    AndroidImportKeys.Quantity,
                    AndroidImportKeys.Supplier,
                    AndroidImportKeys.Category,
                    AndroidImportKeys.TotalPrice,
                    string.Empty,
                    string.Empty
                },
                table.Columns.Select(column => column.CanonicalKey).ToArray());
            Assert.IsTrue(table.Columns.Take(10).All(column => column.HeaderSource == "alias"));
            Assert.IsTrue(table.Columns.Skip(10).All(column => column.HeaderSource == "unknown"));

            Assert.AreEqual(5, table.Rows.Count);
            CollectionAssert.AreEqual(new[] { 4, 5, 6, 7, 9 }, table.Rows.Select(row => row.RowNumber).ToArray());
            Assert.AreEqual("00123456", table.Rows[0].Values[0], "Formatted leading-zero barcode changed.");
            Assert.AreEqual("1234.56", table.Rows[0].Values[4]);
            Assert.AreEqual("2469.12", table.Rows[0].Values[9], "Formatted decimal changed.");
            Assert.AreEqual("TRUE", table.Rows[0].Values[10], "Boolean formatting changed.");
            Assert.AreEqual("2026-08-02", table.Rows[0].Values[11], "Date formatting changed.");
            Assert.AreEqual("1.234,56", table.Rows[1].Values[4]);
            Assert.AreEqual("1,234.56", table.Rows[1].Values[5]);
            Assert.AreEqual("Hidden Product", table.Rows[4].Values[2], "Hidden rows must preserve current behavior.");
            Assert.AreEqual("hidden-flag", table.Rows[4].Values[10], "Hidden columns must preserve current behavior.");

            var existing = new ProductDetailsRow
            {
                Barcode = "123456789012",
                ArticleCode = "OLD-EXISTING",
                Name = "Existing Before",
                Name2 = "Existing Before 2",
                PurchasePrice = 100,
                UnitPrice = 200,
                StockQty = 1,
                SupplierName = "Old Supplier",
                CategoryName = "Old Category"
            };
            var analysis = SupplierImportAnalyzer.Analyze(table, new[] { existing });
