        var canonicalPath = TempPath(".xlsx");
        var headerlessPath = TempPath(".xlsx");
        try
        {
            using (var workbook = new XLWorkbook())
            {
                var sheet = workbook.Worksheets.Add("Canonical");
                var headers = new[]
                {
                    AndroidImportKeys.Barcode,
                    AndroidImportKeys.ProductName,
                    AndroidImportKeys.PurchasePrice,
                    AndroidImportKeys.RetailPrice
                };
                for (var column = 0; column < headers.Length; column++)
                    sheet.Cell(1, column + 1).Value = headers[column];
                sheet.Cell(2, 1).Value = "12345678";
                sheet.Cell(2, 2).Value = "Canonical Product";
                sheet.Cell(2, 3).Value = 100;
                sheet.Cell(2, 4).Value = 180;
                workbook.SaveAs(canonicalPath);
            }

            using (var workbook = new XLWorkbook())
            {
                var sheet = workbook.Worksheets.Add("Headerless");
                var rows = new[]
                {
                    new[] { "1234567890123", "Pattern One", "10", "1.000", "10.000", "AB12", "1.500", "Second One", "Supplier Pattern", "10%", "900", "1" },
                    new[] { "9876543210987", "Pattern Two", "5", "2.000", "10.000", "CD34", "2.500", "Second Two", "Supplier Pattern", "5%", "1900", "2" }
                };
                for (var row = 0; row < rows.Length; row++)
                    for (var column = 0; column < rows[row].Length; column++)
                        sheet.Cell(row + 1, column + 1).Value = rows[row][column];
                workbook.SaveAs(headerlessPath);
            }

