    private static string BuildSnapshot(
        SupplierExcelRawTable table,
        SupplierImportAnalysis analysis,
        SupplierImportSyncPreview preview)
    {
        var builder = new StringBuilder();
        builder.AppendLine($"table|{Escape(table.SheetName)}|{table.HasHeader}|{table.DataRowIndex}|{table.DroppedSummaryRows}");
        foreach (var column in table.Columns)
        {
            builder.AppendLine(
                $"column|{column.ColumnIndex}|{Escape(column.OriginalHeader)}|{Escape(column.DisplayName)}|" +
                $"{Escape(column.CanonicalKey)}|{Escape(column.HeaderSource)}|{Escape(column.Confidence)}|" +
                $"{column.IsEnabled}|{column.IsGenerated}|{Escape(column.SampleValues)}");
        }
        foreach (var row in table.Rows)
            builder.AppendLine($"row|{row.RowNumber}|{string.Join("|", row.Values.Select(Escape))}");
        builder.AppendLine(
            $"analysis|{analysis.HasHeader}|{analysis.DataRowIndex}|{analysis.HeaderRowNumber}|" +
            $"{analysis.SkippedMetadataRows}|{analysis.DroppedSummaryRows}|{analysis.SourceRowCount}|" +
            $"{analysis.EditableRows.Count}|{analysis.NewProducts.Count}|{analysis.UpdatedProducts.Count}");
        foreach (var warning in analysis.Warnings)
            builder.AppendLine($"warning|{Escape(warning.Message)}|{string.Join(",", warning.Rows)}");
        foreach (var error in analysis.Errors)
            builder.AppendLine($"error|{error.RowIndex}|{Escape(error.Barcode)}|{Escape(error.Message)}");
        foreach (var row in analysis.EditableRows)
        {
            builder.AppendLine(
                $"editable|{row.RowNumber}|{Escape(row.Barcode)}|{Escape(row.ItemNumber)}|" +
                $"{Escape(row.ProductName)}|{Escape(row.SecondProductName)}|{Escape(row.PurchasePrice)}|" +
                $"{Escape(row.RetailPrice)}|{Escape(row.Quantity)}|{Escape(row.Supplier)}|" +
                $"{Escape(row.Category)}|{row.Exists}|{row.IsSkipped}");
        }
        builder.AppendLine(
            $"preview|{preview.Summary.TotalRows}|{preview.Summary.NonSkippedRows}|" +
            $"{preview.Summary.NewProducts}|{preview.Summary.UpdatedProducts}|" +
            $"{preview.Summary.NoChangeRows}|{preview.Summary.SkippedRows}|" +
            $"{preview.Summary.WarningCount}|{preview.Summary.ErrorCount}|{preview.CanApply}|" +
            $"{preview.Fingerprint}");
        return builder.ToString();
    }

    private static string Escape(string value)
    {
        return (value ?? string.Empty)
            .Replace("\\", "\\\\")
            .Replace("|", "\\|")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n");
    }

    private static string Sha256(string value)
    {
        using var sha = SHA256.Create();
        return Convert.ToHexString(sha.ComputeHash(Encoding.UTF8.GetBytes(value ?? string.Empty))).ToLowerInvariant();
    }

    private static void AssertColumn(SupplierExcelRawTable table, string key, string source)
    {
        Assert.IsTrue(
            table.Columns.Any(column =>
                string.Equals(column.CanonicalKey, key, StringComparison.Ordinal) &&
                string.Equals(column.HeaderSource, source, StringComparison.Ordinal)),
            $"Expected {key} from {source}.");
    }

    private static Exception CaptureException(Action action)
    {
        try
        {
            action();
        }
        catch (Exception ex)
        {
            return ex;
        }

        Assert.Fail("Expected operation to fail.");
        return new InvalidOperationException("Unreachable");
    }

    private static string TempPath(string extension)
    {
        return Path.Combine(
