            AssertColumn(headerless, AndroidImportKeys.RetailPrice, "pattern");
            AssertColumn(headerless, AndroidImportKeys.SecondProductName, "pattern");
            AssertColumn(headerless, AndroidImportKeys.Supplier, "pattern");
            AssertColumn(headerless, AndroidImportKeys.Discount, "pattern");
            AssertColumn(headerless, AndroidImportKeys.DiscountedPrice, "pattern");
            AssertColumn(headerless, AndroidImportKeys.RowNumber, "pattern");
